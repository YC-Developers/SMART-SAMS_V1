    function exportTableToExcel(tableID, filename = '') {
      var table = document.getElementById(tableID);
      var headerText = table.closest('.card').querySelector('.card-header h6').textContent;
      var province = '<?php echo $p; ?>';
      var district = '<?php echo $d; ?>';
      var schoolName = '<?php echo $s; ?>';
      var schoolCode = '<?php echo $code; ?>';
      
      var html = '<table>' +
                 '<thead>' +
                 '<tr><th colspan="' + table.rows[0].cells.length + '">' + headerText + '</th></tr>' +
                 '<tr><th colspan="' + table.rows[0].cells.length + '">Province: ' + province + '</th></tr>' +
                 '<tr><th colspan="' + table.rows[0].cells.length + '">District: ' + district + '</th></tr>' +
                 '<tr><th colspan="' + table.rows[0].cells.length + '">School Name: ' + schoolName + '</th></tr>' +
                 '<tr><th colspan="' + table.rows[0].cells.length + '">School Code: ' + schoolCode + '</th></tr>' +
                 table.querySelector('thead').innerHTML +
                 '</thead>' +
                 '<tbody>' + table.querySelector('tbody').innerHTML + '</tbody>' +
                 '</table>';
      
      var blob = new Blob(['\ufeff', html], {
        type: 'application/vnd.ms-excel'
      });
      
      filename = filename ? filename + '.xls' : 'excel_data.xls';
      var downloadLink = document.createElement("a");
      document.body.appendChild(downloadLink);
      
      if (navigator.msSaveOrOpenBlob) {
        navigator.msSaveOrOpenBlob(blob, filename);
      } else {
        downloadLink.href = URL.createObjectURL(blob);
        downloadLink.download = filename;
        downloadLink.click();
      }
      
      document.body.removeChild(downloadLink);
    }

    function exportToPDF(tableID, filename = '') {
      const { jsPDF } = window.jspdf;
      const doc = new jsPDF();
      
      // Get header text and school details
      var headerText = document.getElementById(tableID)
        .closest('.card')
        .querySelector('.card-header h6')
        .textContent;
      var province = '<?php echo $p; ?>';
      var district = '<?php echo $d; ?>';
      var schoolName = '<?php echo $s; ?>';
      var schoolCode = '<?php echo $code; ?>';
      
      // Add header and school details
      doc.setFontSize(12);
      doc.text(headerText, 14, 20);
      doc.setFontSize(10);
      doc.text('Province: ' + province, 14, 30);
      doc.text('District: ' + district, 14, 35);
      doc.text('School Name: ' + schoolName, 14, 40);
      doc.text('School Code: ' + schoolCode, 14, 45);
      
      // Add table
      const table = document.getElementById(tableID);
      doc.autoTable({
        html: table,
        startY: 50,
        styles: {
          fontSize: 8,
          cellPadding: 2
        },
        columnStyles: {
          0: {cellWidth: 10},
          1: {cellWidth: 40}
        }
      });
      
      filename = filename ? filename + '.pdf' : 'document.pdf';
      doc.save(filename);
    }
